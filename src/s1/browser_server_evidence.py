"""Optional local server evidence; server computation does not prove HTTP delivery."""

from __future__ import annotations

import copy
import hashlib
import json
import math
import os
import re
import threading
import time
from pathlib import Path


def json_evidence(value, depth=0):
    """Detach provider output without hiding invalid or non-JSON values."""
    if depth > 64:
        return {"evidence_error": "nesting exceeds 64 levels"}
    if isinstance(value, dict):
        if any(not isinstance(key, str) for key in value):
            return {
                "non_json_mapping": [
                    {"key": json_evidence(key, depth + 1), "value": json_evidence(item, depth + 1)}
                    for key, item in value.items()
                ]
            }
        return {key: json_evidence(item, depth + 1) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [json_evidence(item, depth + 1) for item in value]
    if type(value) is float and not math.isfinite(value):
        return {"nonfinite_float": repr(value)}
    if value is None or type(value) in (str, int, float, bool):
        return value
    return {"non_json_type": type(value).__qualname__}


class ServerEvidenceJournal:
    """Append/fsync request events beneath one caller-owned, new directory.

    IDs are generated by the API, never taken from a payload. A snapshot is a
    point-in-time index: an unfinished worker may append after runner cleanup.
    Failed writes are visible and prevent a request from being called sealed.
    """

    def __init__(self, directory):
        self.directory = Path(directory).resolve()
        self.directory.mkdir(parents=True, exist_ok=False)
        self._lock = threading.Lock()
        self._requests = {}
        self._errors = []

    def __call__(self, event):
        request_id = event.get("request_id")
        sequence = event.get("sequence")
        name = event.get("event")
        try:
            if not isinstance(request_id, str) or not re.fullmatch(r"[0-9a-f]{32}", request_id):
                raise ValueError("Evidence request ID must be generated by the server")
            if type(sequence) is not int or sequence < 0 or not isinstance(name, str):
                raise ValueError("Evidence events need an integer sequence and event name")
            with self._lock:
                record = self._requests.setdefault(
                    request_id,
                    {
                        "request_id": request_id,
                        "path": request_id + ".jsonl",
                        "last_sequence": -1,
                        "last_event": None,
                        "server_status": "in_flight",
                        "sealed": False,
                        "events": 0,
                        "bytes": 0,
                        "write_failed": False,
                        "created": False,
                    },
                )
                if sequence <= record["last_sequence"]:
                    raise ValueError("Evidence events must retain their server sequence order")
                blob = (
                    json.dumps(event, ensure_ascii=False, separators=(",", ":"), allow_nan=False)
                    + "\n"
                ).encode()
                path = self.directory / record["path"]
                with path.open("ab" if record["created"] else "xb") as handle:
                    record["created"] = True
                    handle.write(blob)
                    handle.flush()
                    os.fsync(handle.fileno())
                record["bytes"] += len(blob)
                record["events"] += 1
                record["last_sequence"], record["last_event"] = sequence, name
                if name in {"server_returned", "server_failed"}:
                    record["server_status"] = name
                    record["sealed"] = not record["write_failed"]
        except BaseException as exc:
            with self._lock:
                record = self._requests.get(request_id) if isinstance(request_id, str) else None
                if record is not None:
                    record.update(write_failed=True, sealed=False)
                self._errors.append(
                    {
                        "request_id": request_id if isinstance(request_id, str) else None,
                        "sequence": sequence if type(sequence) is int else None,
                        "event": name if isinstance(name, str) else None,
                        "type": type(exc).__name__,
                        "message": str(exc),
                    }
                )
            raise

    def snapshot(self):
        with self._lock:
            requests = [dict(row) for row in self._requests.values()]
            for row in requests:
                # Hash actual on-disk bytes, including any incomplete failed
                # write. Such a request remains explicitly unsealed.
                path = self.directory / row["path"]
                blob = path.read_bytes() if row["created"] else b""
                row["successful_event_bytes"] = row["bytes"]
                row["bytes"], row["sha256"] = len(blob), hashlib.sha256(blob).hexdigest()
            return {
                "schema_version": 1,
                "snapshot_unix": time.time(),
                "scope": "server computation only; HTTP client receipt is unknown",
                "durability": "JSONL events flushed and fsynced; snapshot hashes cover actual file bytes, including incomplete failed writes",
                "requests": requests,
                "pending_request_ids": [
                    row["request_id"] for row in requests if row["server_status"] == "in_flight"
                ],
                "all_requests_sealed": all(row["sealed"] for row in requests),
                "errors": copy.deepcopy(self._errors),
            }
